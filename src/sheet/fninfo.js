// { EN: { en, ru, category, args: [{ name, optional, more }], description } }
export const FN_INFO = {};
for (const line of RAW.trim().split('\n')) {
  const [en, category, args, description] = line.split('|');
  FN_INFO[en] = {
    en, category, description, ru: ruName(en),
    args: args ? args.split(';').filter((a) => a !== '…').map((a) => ({ name: a.replace(/^\[|\]$/g, ''), optional: a.startsWith('[') })) : [],
    more: args.includes('…'),
  };
}
// функции движка без описания — хотя бы с именем (не должно случаться: проверяется тестом)
for (const en of [...FUNCTIONS, 'IF', 'IFERROR', 'IFS', 'SWITCH', 'IFNA', 'LET']) {
  if (!FN_INFO[en]) FN_INFO[en] = { en, ru: ruName(en), category: I, description: '', args: [], more: true };
}
export const FN_LIST = Object.values(FN_INFO).sort((a, b) => a.ru.localeCompare(b.ru, 'ru'));

// Подпись функции для подсказки: СУММ(число1; [число2]; …)
export function signature(info) {
  const parts = info.args.map((a) => (a.optional ? `[${a.name}]` : a.name));
  if (info.more) parts.push('…');
  return `${info.ru}(${parts.join('; ')})`;
}
// Номер аргумента k в подписи (для повторяющихся — последний «повторяемый»)
export const argIndex = (info, k) => (k < info.args.length ? k : info.more ? info.args.length - 1 : -1);
